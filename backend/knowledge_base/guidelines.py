def retrieve(defect_class=None, extra_query=""):
    """Простой retrieval: приоритет — точное совпадение по классу дефекта,
    затем общие записи, релевантные по ключевым словам запроса."""
    results = [k for k in KB if k["defect_class"] == defect_class] if defect_class else []
    generic = [k for k in KB if k["defect_class"] is None]
    if extra_query:
        q = extra_query.lower()
        generic = sorted(generic, key=lambda k: -sum(w in k["text"].lower() for w in q.split()))
    results.extend(generic)
    return results
